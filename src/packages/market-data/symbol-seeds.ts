/**
 * Tablas del catálogo.
 *
 * Son datos, no lógica: cada fila es un instrumento que existe de verdad y que
 * se comprobó contra la fuente antes de entrar aquí -ticker válido, precio
 * positivo y divisa declarada-. La lógica que las convierte en instrumentos
 * vive en `symbols.ts`, y separarlas evita que un fichero de trescientas líneas
 * de datos entierre las veinte que deciden algo.
 *
 * `basePrice` solo alimenta al motor determinístico de la fuente sintética y a
 * la presentación por defecto; el precio que ve la persona siempre viene de la
 * fuente real. Se guarda el valor observado el día que se añadió el
 * instrumento, que es una referencia de orden de magnitud y no una cotización.
 */

