// Anonymous production smoke only. No customer session, trade, charge or signup.
import assert from 'node:assert/strict';

const base = 'https://tradinglab--nexant-87204.us-east4.hosted.app';
const request = (path, init = {}) => fetch(base + path, { redirect: 'manual', signal: AbortSignal.timeout(25000), ...init });
const manifestResponse = await request('/manifest.webmanifest');
assert.equal(manifestResponse.status, 200);
const manifest = await manifestResponse.json();
assert.equal(manifest.name, 'TradingLab');
assert.equal(manifest.short_name, 'TradingLab');
assert.equal(manifest.start_url, '/app');
assert.equal(manifest.display, 'standalone');
const appResponse = await request('/app');
assert.equal(appResponse.status, 200);
const html = await appResponse.text();
assert.match(html, /<title>TradingLab<\/title>/);
assert.match(html, /welcome-app/);
assert.match(html, /Un mundo de mercados/);
const worker = await request('/sw.js');
assert.equal(worker.status, 200);
assert.match(await worker.text(), /tradinglab-public-v4/);
const pulse = await request('/api/market/pulse?symbol=BTCUSD');
assert.equal(pulse.status, 401);
assert.match(pulse.headers.get('cache-control') ?? '', /no-store/);
const terminal = await request('/terminal');
assert([303, 307].includes(terminal.status));
assert.equal(new URL(terminal.headers.get('location'), base).pathname, '/entrar');
const sourceResponse = await request('/api/market/status');
assert.equal(sourceResponse.status, 200);
const sources = await sourceResponse.json();
assert.equal(sources.realOnly, true);
assert.deepEqual(sources.instruments.map(item => item.symbol), ['BTCUSDT', 'ETHUSDT', 'SOLUSDT']);
assert(sources.instruments.every(item => item.available && item.source === 'binance-spot-v1'), 'All enabled pairs must reach their real provider from production');
const events = await request('/api/payments/wompi/events');
assert.equal(events.status, 200);
const health = (await events.json()).data;
assert.equal(health.service, 'wompi-events');
assert.equal(health.environment, 'production');
assert.equal(health.checkoutEnabled, true);
// Authentication must reject before creating a payment intent.
const subscribe = await request('/api/billing/subscribe', { method: 'POST', headers: { Origin: base, 'Content-Type': 'application/json' }, body: '{}' });
assert.equal(subscribe.status, 401);
const foreign = await request('/api/billing/subscribe', { method: 'POST', headers: { Origin: 'https://untrusted.example.invalid', 'Content-Type': 'application/json' }, body: '{}' });
assert.equal(foreign.status, 403);
